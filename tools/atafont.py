"""Font 8x8 of ATASCII for SAPI-Term (own design): build/font_ata.inc.

128 glyphs by the ATASCII code 00h-7Fh (80h-FFh are the same in inverse video, drawn with the colours swapped):
letters, digits and signs are the font 4x8 of SAPI-Term with each dot doubled (as in tools/petfont.py), the
graphics 00h-1Fh, 60h and 7Bh-7Fh are drawn here from what each character means (the ATASCII article of
Wikipedia lists them as Unicode). Nothing is taken from an Atari ROM. Also and_map_ata for the AND-1V.
  python tools/atafont.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fontgen  # noqa: E402
import petfont as pf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

HAND = {
    'esc': ['.######.', '##....##', '#.###..#', '#.#....#', '#.##...#', '#.###..#', '##....##', '.######.'],
    'up': ['...##...', '..####..', '.######.', '...##...', '...##...', '...##...', '...##...', '........'],
    'left': ['........', '..##....', '.##.....', '#######.', '.##.....', '..##....', '........', '........'],
    'clear': ['..#.....', '.##.....', '######..', '.##..#..', '..#..#..', '.....#..', '.....#..', '........'],
    'tri_left': ['......##', '....####', '..######', '########', '..######', '....####', '......##', '........'],
}
UP = pf.grid(HAND['up'])
LEFT = pf.grid(HAND['left'])
TRI_LEFT = pf.grid(HAND['tri_left'])

GRAPHICS = {
    0x00: pf.grid(pf.HAND['heart']),
    0x01: pf.box(1, 1, 0, 1),                               # ├
    0x02: pf.cells(lambda x, y: x >= 6),                    # right quarter
    0x03: pf.box(1, 0, 1, 0),                               # ┘
    0x04: pf.box(1, 1, 1, 0),                               # ┤
    0x05: pf.box(0, 1, 1, 0),                               # ┐
    0x06: pf.mirror_x(pf.DIAG),                             # ╱
    0x07: pf.DIAG,                                          # ╲
    0x08: pf.cells(lambda x, y: x + y >= 7),                # ◢
    0x09: pf.cells(lambda x, y: x >= 4 and y >= 4),         # ▗
    0x0A: pf.cells(lambda x, y: x <= y),                    # ◣
    0x0B: pf.cells(lambda x, y: x >= 4 and y < 4),          # ▝
    0x0C: pf.cells(lambda x, y: x < 4 and y < 4),           # ▘
    0x0D: pf.cells(lambda x, y: y < 2),                     # upper quarter
    0x0E: pf.cells(lambda x, y: y >= 6),                    # ▂
    0x0F: pf.cells(lambda x, y: x < 4 and y >= 4),          # ▖
    0x10: pf.grid(pf.HAND['club']),
    0x11: pf.box(0, 1, 0, 1),                               # ┌
    0x12: pf.box(0, 0, 1, 1),                               # ─
    0x13: pf.box(1, 1, 1, 1),                               # ┼
    0x14: pf.grid(pf.HAND['dot']),                          # •
    0x15: pf.cells(lambda x, y: y >= 4),                    # ▄
    0x16: pf.cells(lambda x, y: x < 2),                     # ▎
    0x17: pf.box(0, 1, 1, 1),                               # ┬
    0x18: pf.box(1, 0, 1, 1),                               # ┴
    0x19: pf.cells(lambda x, y: x < 4),                     # ▌
    0x1A: pf.box(1, 0, 0, 1),                               # └
    0x1B: pf.grid(HAND['esc']),                             # ␛
    0x1C: UP,                                               # ↑
    0x1D: pf.mirror_y(UP),                                  # ↓
    0x1E: LEFT,                                             # ←
    0x1F: pf.mirror_x(LEFT),                                # →
    0x60: pf.grid(pf.HAND['diamond']),
    0x7B: pf.grid(pf.HAND['spade']),
    0x7D: pf.grid(HAND['clear']),                           # the clear screen arrow
    0x7E: TRI_LEFT,                                         # ◀
    0x7F: pf.mirror_x(TRI_LEFT),                            # ▶
}


def build():
    cp = fontgen.parse()['cp437']
    return [GRAPHICS[c] if c in GRAPHICS else pf.doubled(cp[c]) for c in range(128)]


AND_GRAPHICS = {0x01: pf.AND_BOX[(1, 1, 0, 1)], 0x03: pf.AND_BOX[(1, 0, 1, 0)], 0x04: pf.AND_BOX[(1, 1, 1, 0)],
                0x05: pf.AND_BOX[(0, 1, 1, 0)], 0x11: pf.AND_BOX[(0, 1, 0, 1)], 0x12: pf.AND_BOX[(0, 0, 1, 1)],
                0x13: pf.AND_BOX[(1, 1, 1, 1)], 0x17: pf.AND_BOX[(0, 1, 1, 1)], 0x18: pf.AND_BOX[(1, 0, 1, 1)],
                0x1A: pf.AND_BOX[(1, 0, 0, 1)], 0x06: ord('/'), 0x07: ord('\\'), 0x00: ord('*'), 0x10: ord('*'),
                0x60: ord('*'), 0x7B: ord('*'), 0x14: ord('o'), 0x1B: ord('E'), 0x1C: 0x5E, 0x1D: ord('v'),
                0x1E: ord('<'), 0x1F: ord('>'), 0x7D: ord('^'), 0x7E: ord('<'), 0x7F: ord('>'), 0x7C: ord('|')}


def and_map(glyphs):
    m = []
    for c in range(128):
        if c in AND_GRAPHICS:
            m.append(AND_GRAPHICS[c])
        elif c in GRAPHICS:
            m.append(pf.and_semi(glyphs[c]))
        else:
            m.append(c)
    return m


def main():
    glyphs = build()
    out = ['; Generated by tools/atafont.py, do not edit. Follows font_pet (on a page boundary).',
           '; font_ata: 128 glyphs 8x8 of ATASCII 00h-7Fh, dots D7 (left) to D0; and_map_ata: the same as characters',
           '; of the AND-1V.', '', 'font_ata:']
    for code, g in enumerate(glyphs):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in pf.glyph_bytes(g)), code))
    out.append('and_map_ata:')
    m = and_map(glyphs)
    for i in range(0, 128, 16):
        out.append('        defb ' + ','.join('%03Xh' % v for v in m[i:i + 16]))
    path = os.path.join(ROOT, 'build', 'font_ata.inc')
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
    print('build/font_ata.inc: 128 glyphs 8x8')


if __name__ == '__main__':
    main()

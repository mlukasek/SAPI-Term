"""Font 8x8 of ATASCII for SAPI-Term: fonts/atari.txt (the font of the Atari 400/800, tools/romfont.py) ->
build/font_ata.inc.

128 glyphs by the ATASCII code 00h-7Fh (80h-FFh are the same in inverse video, drawn with the colours swapped).
Also and_map_ata for the AND-1V, and vdt_extra: the characters of the British teletext set ATASCII lacks
(src/vdt.asm: £ ½ ¼ ¾ ‖ ÷ ■): the pound of the C64, ½ ¼ ÷ the font 4x8 of SAPI-Term doubled, the rest drawn here.
  python tools/atafont.py [--preview build/preview/font_ata.png]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fontgen  # noqa: E402
import petfont as pf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'atari.txt')

# the graphics (on the AND-1V by AND_GRAPHICS or their 2x3 look); the rest are letters, digits and signs
GRAPHICS = set(range(0x20)) | {0x60, 0x7B, 0x7D, 0x7E, 0x7F}

VDT_HAND = {
    'three_quarters': ['##......', '..#.....', '##...#..', '..#.#...', '##.#.##.', '..#.#.#.', '.#..####', '......#.'],
    'double_bar': ['.##..##.', '.##..##.', '.##..##.', '.##..##.', '.##..##.', '.##..##.', '.##..##.', '.##..##.'],
}


def vdt_extra():
    """£ ½ ¼ ¾ ‖ ÷ ■ (Viewdata 23h, 5Ch, 7Bh, 7Dh, 7Ch, 7Eh, 7Fh)."""
    cp = fontgen.parse()['cp437']
    pound = pf.build()[0x1C]
    return [pound, pf.doubled(cp[0xAB]), pf.doubled(cp[0xAC]), pf.grid(VDT_HAND['three_quarters']),
            pf.grid(VDT_HAND['double_bar']), pf.doubled(cp[0xF6]), pf.cells(lambda x, y: True)]


def build():
    font = fontgen.parse(SRC)['atascii']
    return [pf.grid(font[c]) for c in range(128)]


AND_GRAPHICS = {0x01: pf.AND_BOX[(1, 1, 0, 1)], 0x03: pf.AND_BOX[(1, 0, 1, 0)], 0x04: pf.AND_BOX[(1, 1, 1, 0)],
                0x05: pf.AND_BOX[(0, 1, 1, 0)], 0x11: pf.AND_BOX[(0, 1, 0, 1)], 0x12: pf.AND_BOX[(0, 0, 1, 1)],
                0x13: pf.AND_BOX[(1, 1, 1, 1)], 0x17: pf.AND_BOX[(0, 1, 1, 1)], 0x18: pf.AND_BOX[(1, 0, 1, 1)],
                0x1A: pf.AND_BOX[(1, 0, 0, 1)], 0x06: ord('/'), 0x07: ord('\\'), 0x00: ord('*'), 0x10: ord('*'),
                0x60: ord('*'), 0x7B: ord('*'), 0x14: ord('o'), 0x1B: ord('E'), 0x1C: 0x5E, 0x1D: ord('v'),
                0x1E: ord('<'), 0x1F: ord('>'), 0x7D: ord('^'), 0x7E: ord('<'), 0x7F: ord('>'), 0x7C: ord('|')}


def and_map(glyphs):
    m = []
    for c in range(128):
        if c in AND_GRAPHICS:
            m.append(AND_GRAPHICS[c])
        elif c in GRAPHICS:
            m.append(pf.and_semi(glyphs[c]))
        else:
            m.append(c)
    return m


def main():
    glyphs = build()
    out = ['; Generated by tools/atafont.py, do not edit. Follows font_pet (on a page boundary).',
           '; font_ata: 128 glyphs 8x8 of ATASCII 00h-7Fh, dots D7 (left) to D0; and_map_ata: the same as characters',
           '; of the AND-1V.', '', 'font_ata:']
    for code, g in enumerate(glyphs):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in pf.glyph_bytes(g)), code))
    out.append('and_map_ata:')
    m = and_map(glyphs)
    for i in range(0, 128, 16):
        out.append('        defb ' + ','.join('%03Xh' % v for v in m[i:i + 16]))
    out.append('vdt_extra:                      ; the pound, 1/2, 1/4, 3/4, double bar, divide, block (vdt.asm)')
    for g in vdt_extra():
        out.append('        defb %s' % ','.join('%03Xh' % b for b in pf.glyph_bytes(g)))
    path = os.path.join(ROOT, 'build', 'font_ata.inc')
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
    print('build/font_ata.inc: 128 glyphs 8x8')
    if '--preview' in sys.argv:
        pf.preview(glyphs, sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()

"""Font 4x8 of SAPI-Term: fonts/sapiterm4x8.txt -> build/font4x8.inc (+ a preview PNG).

build/font4x8.inc: font_cp437 (256 glyphs) and font_koi (KOI-8cs2 C0-FF), 8 bytes per glyph, the 4 dots of a row
in D7..D4 (D7 = left), D3..D0 = 0 (there the CGA-1V takes the attribute). The include must start on a page
boundary (src/sapiterm.asm aligns it).
  python tools/fontgen.py [--preview build/preview/font4x8.png]
"""
import os
import re
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'sapiterm4x8.txt')


def parse(path=SRC):
    """{'cp437': {code: [8 rows of '#.']}, 'koi8cs': {...}}"""
    banks, bank, codes, row = {}, None, None, 0
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        m = re.match(r'\[(\w+)\]$', line.strip())
        if m:
            bank = banks.setdefault(m.group(1), {})
            codes = None
            continue
        tokens = line.split()
        if all(re.fullmatch(r'[#.]{4}', t) for t in tokens):
            if codes is None or row >= 8 or len(tokens) != len(codes):
                sys.exit('%s:%d: glyph row without a header or with %d glyphs' % (path, n, len(tokens)))
            for c, t in zip(codes, tokens):
                bank[c].append(t)
            row += 1
        else:
            codes = [int(t, 16) for t in tokens if re.fullmatch(r'[0-9A-F]{2}', t)]
            if not codes:
                sys.exit('%s:%d: no codes in a header line' % (path, n))
            for c in codes:
                if c in bank:
                    sys.exit('%s:%d: code %02X twice' % (path, n, c))
                bank[c] = []
            row = 0
    for name, glyphs in banks.items():
        for c, rows in glyphs.items():
            if len(rows) != 8:
                sys.exit('%s: [%s] %02X has %d rows' % (path, name, c, len(rows)))
    return banks


def glyph_bytes(rows):
    return [sum(0x80 >> i for i, ch in enumerate(r) if ch == '#') for r in rows]


def write_inc(banks, path):
    cp, koi = banks['cp437'], banks['koi8cs']
    assert sorted(cp) == list(range(256)), 'cp437 must have 00-FF'
    assert sorted(koi) == list(range(0xC0, 0x100)), 'koi8cs must have C0-FF'
    out = ['; Generated by tools/fontgen.py from fonts/sapiterm4x8.txt, do not edit.',
           '; 8 bytes per glyph, dots in D7..D4 (D7 = left). Starts on a page boundary.', '',
           'font_cp437:']
    for c in range(256):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in glyph_bytes(cp[c])), c))
    out.append('font_koi:                       ; KOI-8cs2 C0-FF')
    for c in range(0xC0, 0x100):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in glyph_bytes(koi[c])), c))
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')


def png(path, w, h, rgb):
    """rgb: bytes of w*h*3."""
    raw = b''.join(b'\0' + rgb[y * w * 3:(y + 1) * w * 3] for y in range(h))

    def chunk(kind, body):
        return struct.pack('>I', len(body)) + kind + body + struct.pack('>I', zlib.crc32(kind + body))
    data = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 2, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    open(path, 'wb').write(data)


def preview(banks, path):
    """Both banks as tables of 16 glyphs per row, a dot 2x2 like the VGA of the CGA-1V, then scaled 2x."""
    cp, koi = banks['cp437'], banks['koi8cs']
    cells = [cp[c] for c in range(256)] + [koi[c] for c in range(0xC0, 0x100)]
    cols, gap = 16, 2
    cw, ch = 4 + gap, 8 + gap
    rows = (len(cells) + cols - 1) // cols + 1
    W, H = cols * cw + gap, rows * ch + gap
    px = [[0] * W for _ in range(H)]
    for i, g in enumerate(cells):
        r = i // cols + (1 if i >= 256 else 0)
        x0, y0 = gap + (i % cols) * cw, gap + r * ch
        for y in range(8):
            for x in range(4):
                if g[y][x] == '#':
                    px[y0 + y][x0 + x] = 1
                elif x == 3 or y >= 6:
                    px[y0 + y][x0 + x] = 2      # the gap column and the descender rows, faintly
    scale = 4
    fg, bg, faint = b'\xff\xb0\x00', b'\x16\x17\x1a', b'\x22\x24\x29'
    out = bytearray()
    for y in range(H * scale):
        line = b''.join({0: bg, 1: fg, 2: faint}[px[y // scale][x // scale]] for x in range(W * scale))
        out += line
    png(path, W * scale, H * scale, bytes(out))


def main():
    banks = parse()
    os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
    write_inc(banks, os.path.join(ROOT, 'build', 'font4x8.inc'))
    if '--preview' in sys.argv:
        p = sys.argv[sys.argv.index('--preview') + 1]
        os.makedirs(os.path.dirname(os.path.abspath(p)), exist_ok=True)
        preview(banks, p)
        print('preview', p)
    print('build/font4x8.inc: %d + %d glyphs' % (len(banks['cp437']), len(banks['koi8cs'])))


if __name__ == '__main__':
    main()

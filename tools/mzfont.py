"""Font 8x8 of the Sharp MZ-800 for ANSI in 40 columns: fonts/mz800.txt and fonts/mz800cs.txt (the Czech and Slovak
letters as the Czech CP/M of the MZ-800 shows them; both by tools/romfont.py) -> build/font_mz.inc.

font_mz: 8 bytes a glyph, dots D7 (left) to D0, 8-aligned: CP437 20h-7Fh (glyphs 0-5Fh), then the characters of
CP437 outside ASCII the MZ has (mz_extra: code, glyph; MZ_EXTRA_N pairs), then the letters of KOI-8cs2 (mz_koi:
C0h-FFh -> glyph, the codes without a letter a space). src/cgatext.asm glyph_addr takes them in 40 columns; all
other characters are the font 4x8 with its dots doubled.
  python tools/mzfont.py [--preview build/preview/font_mz.png]
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fontgen  # noqa: E402
import petfont as pf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'mz800.txt')
SRC_CS = os.path.join(ROOT, 'fonts', 'mz800cs.txt')
KOI_ASCII = {0xFF: 0x3F}                        # ? as in font_koi


def layout():
    """(glyphs in their order, {CP437 code: glyph index}, [64 glyph indexes for KOI C0-FF])."""
    mz = fontgen.parse(SRC)
    cs = fontgen.parse(SRC_CS)['koi8cs']
    glyphs = [mz['ascii'][c] for c in range(0x20, 0x80)]
    cp437 = {c: c - 0x20 for c in range(0x20, 0x80)}
    for c in sorted(mz['cp437']):
        cp437[c] = len(glyphs)
        glyphs.append(mz['cp437'][c])
    koi = []
    for c in range(0xC0, 0x100):
        if c in cs:
            koi.append(len(glyphs))
            glyphs.append(cs[c])
        else:
            koi.append(cp437[KOI_ASCII.get(c, 0x20)])
    return glyphs, cp437, koi


def build():
    """{'cp437': {code: glyph}, 'koi': {code: glyph}} as the terminal draws them in 40 columns."""
    glyphs, cp437, koi = layout()
    return {'cp437': {c: pf.grid(glyphs[i]) for c, i in cp437.items()},
            'koi': {0xC0 + n: pf.grid(glyphs[i]) for n, i in enumerate(koi)}}


def main():
    glyphs, cp437, koi = layout()
    extra = sorted((c, i) for c, i in cp437.items() if not 0x20 <= c < 0x80)
    out = ['; Generated by tools/mzfont.py, do not edit. font_mz 8-aligned (cga_draw_8).',
           '; font_mz: glyphs 8x8 of the Sharp MZ-800 for 40 columns, dots D7 (left) to D0: 00-5Fh CP437 20h-7Fh,',
           '; then the CP437 characters of mz_extra, then the Czech and Slovak letters of mz_koi.', '',
           'MZ_EXTRA_N      equ %d' % len(extra),
           'mz_extra:                       ; CP437 code, glyph',
           '        defb ' + ','.join('%03Xh,%03Xh' % p for p in extra),
           'mz_koi:                         ; KOI-8cs2 C0h-FFh -> glyph']
    for i in range(0, 64, 16):
        out.append('        defb ' + ','.join('%03Xh' % v for v in koi[i:i + 16]))
    out.append('        defs (8 - ($ & 7)) & 7')
    out.append('font_mz:')
    for i, g in enumerate(glyphs):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in pf.glyph_bytes(pf.grid(g))), i))
    path = os.path.join(ROOT, 'build', 'font_mz.inc')
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
    print('build/font_mz.inc: %d glyphs 8x8 (%d CP437 outside ASCII)' % (len(glyphs), len(extra)))
    if '--preview' in sys.argv:
        pf.preview([pf.grid(g) for g in glyphs], sys.argv[sys.argv.index('--preview') + 1])


if __name__ == '__main__':
    main()

"""Font 8x8 of the Sharp MZ-700 for ANSI in 40 columns: fonts/mz700.txt (tools/romfont.py) -> build/font_mz.inc.

font_mz: the glyphs of CP437 20h-7Fh (ASCII and the house 7Fh), 8 bytes each, dots D7 (left) to D0, 8-aligned;
src/cgatext.asm glyph_addr takes them in 40 columns instead of the font 4x8 with its dots doubled.
  python tools/mzfont.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fontgen  # noqa: E402
import petfont as pf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'fonts', 'mz700.txt')
FIRST, LAST = 0x20, 0x7F


def build():
    """{code: glyph} for CP437 20h-7Fh."""
    font = fontgen.parse(SRC)['ascii']
    return {c: pf.grid(font[c]) for c in range(FIRST, LAST + 1)}


def main():
    glyphs = build()
    out = ['; Generated by tools/mzfont.py, do not edit. 8-aligned (cga_draw_8).',
           '; font_mz: CP437 20h-7Fh in the font of the Sharp MZ-700 for 40 columns, dots D7 (left) to D0.', '',
           'font_mz:']
    for code in range(FIRST, LAST + 1):
        out.append('        defb %s   ; %02X' % (','.join('%03Xh' % b for b in pf.glyph_bytes(glyphs[code])), code))
    path = os.path.join(ROOT, 'build', 'font_mz.inc')
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
    print('build/font_mz.inc: %d glyphs 8x8' % len(glyphs))


if __name__ == '__main__':
    main()

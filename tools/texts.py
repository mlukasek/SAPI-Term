"""Texts of the SAPI-Term user interface: src/texts.txt (UTF-8) -> build/texts.inc (KOI-8cs2).

src/texts.txt: one text per line, "name text" (name = asm label, the text after one space, may contain
anything that KOI-8cs2 has); "\\" at the end of a line continues the text on the next one; lines starting
with "#" are comments. Each text becomes "name: defb ...,0". The codes C0-FF are Czech letters: the AND-1V
shows them as they are, the CGA-1V takes them from font_koi.
  python tools/texts.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tables import KOI  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUBST = {'–': '-', '—': '-', '×': 'x', '…': '...', '„': '"', '“': '"', '‚': "'", '‘': "'"}


def encode(text, where):
    out = []
    for ch in text:
        ch = SUBST.get(ch, ch)
        for c in ch:
            if c in KOI:
                out.append(KOI[c])
            elif 0x20 <= ord(c) < 0x7F:
                out.append(ord(c))
            else:
                sys.exit('%s: KOI-8cs2 has no %r' % (where, c))
    return out


def main():
    src = os.path.join(ROOT, 'src', 'texts.txt')
    out = ['; Generated by tools/texts.py from src/texts.txt, do not edit. Texts in KOI-8cs2, 00h at the end.', '']
    name, text, n0 = None, '', 0
    lines = open(src, encoding='utf-8').read().split('\n')
    for n, line in enumerate(lines + [''], 1):
        if name is None:
            if not line.strip() or line.startswith('#'):
                continue
            name, _, text = line.partition(' ')
            n0 = n
        else:
            text += line
        if text.endswith('\\'):
            text = text[:-1]
            continue
        codes = encode(text, 'src/texts.txt:%d' % n0) + [0]
        out.append('%s:' % name)
        for i in range(0, len(codes), 16):
            out.append('        defb ' + ','.join('%03Xh' % c for c in codes[i:i + 16]))
        name, text = None, ''
    path = os.path.join(ROOT, 'build', 'texts.inc')
    open(path, 'w', encoding='ascii', newline='\n').write('\n'.join(out) + '\n')
    print('build/texts.inc')


if __name__ == '__main__':
    main()
